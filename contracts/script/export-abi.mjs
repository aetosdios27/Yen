import { execFileSync, spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repo = fileURLToPath(new URL("../../", import.meta.url));
const gitSha =
  process.env.YEN_BUILD_SHA ??
  execFileSync("git", ["rev-parse", "HEAD"], { cwd: repo, encoding: "utf8" }).trim();
const artifact = JSON.parse(
  readFileSync(resolve(repo, "contracts/out/RootRegistry.sol/RootRegistry.json"), "utf8"),
);
const target = "packages/shared/src/registry/abi.ts";
if (process.argv.slice(2).some((arg) => arg !== "--check")) {
  throw new Error("Usage: node contracts/script/export-abi.mjs [--check]");
}
if (!Array.isArray(artifact.abi) || artifact.abi.length === 0) {
  throw new Error("Missing RootRegistry ABI; run forge build first");
}

const source = `// Generated by contracts/script/export-abi.mjs. Do not edit by hand.
export const rootRegistryAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;

export type RootRegistryAddress = \`0x\${string}\`;
// No deployment exists yet. Resolve a verified deployment manifest before use.
export const rootRegistryAddress: RootRegistryAddress | null = null;

// Commit identifier embedded in the ABI so released artifacts and the ABI agree.
export const rootRegistryAbiCommit = ${JSON.stringify(gitSha)};
export const rootRegistryAbiGitSha = ${JSON.stringify(gitSha)};
export const rootRegistryBuildSha = ${JSON.stringify(gitSha)};
`;
const formatted = spawnSync(
  resolve(repo, "node_modules/.bin/biome"),
  ["format", `--stdin-file-path=${target}`],
  { cwd: repo, input: source, encoding: "utf8" },
);
if (formatted.error) throw formatted.error;
if (formatted.status !== 0) throw new Error(formatted.stderr);

if (process.argv.includes("--check")) {
  if (readFileSync(resolve(repo, target), "utf8") !== formatted.stdout) {
    throw new Error(`Stale ABI: run node contracts/script/export-abi.mjs and commit ${target}`);
  }
  console.log("RootRegistry ABI matches the build artifact.");
} else {
  writeFileSync(resolve(repo, target), formatted.stdout);
  console.log(`Generated ${target}`);
}
